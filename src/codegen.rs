//! C code generation.
//!
//! The generated C is ordinary C11 plus GNU statement expressions (supported by
//! clang and gcc). Every Quill `str` is a `QStr*`, every array a `QArr*`, and
//! integer arithmetic calls checked runtime helpers.

use std::collections::HashMap;

use crate::ast::*;
use crate::diag::SourceFile;

pub fn generate(program: &Program, file: &SourceFile) -> String {
    let mut generator = Generator {
        program,
        file,
        scopes: Vec::new(),
        next_id: 0,
        depth: 1,
        ret: Type::void(Default::default()),
    };

    let mut out = String::new();
    out.push_str("/* Generated by quillc. Do not edit by hand. */\n");
    out.push_str("#include <stdint.h>\n");
    out.push_str("#include <stdbool.h>\n");
    out.push_str("#include \"quill_rt.h\"\n");
    // Add user-specified library includes. Bundled libraries live next to the
    // generated C (so they use quotes); system libraries use angle brackets.
    for add in &program.adds {
        if crate::bundled_source(&add.library).is_some() {
            out.push_str(&format!("#include \"{}\"\n", add.library));
        } else {
            out.push_str(&format!("#include <{}>\n", add.library));
        }
    }
    out.push('\n');

    for def in generator.ordered_structs() {
        out.push_str(&format!("typedef struct s_{} {{\n", mangle(&def.name)));
        for field in &def.fields {
            out.push_str(&format!(
                "    {} m_{};\n",
                ctype(&field.ty),
                mangle(&field.name)
            ));
        }
        out.push_str(&format!("}} s_{};\n\n", mangle(&def.name)));
    }

    // Extern function declarations (from extern blocks). When a header is added
    // with `#add`, that header declares its functions already; redeclaring them
    // with Quill's `int64_t` types can conflict, so we only emit declarations
    // for programs that bring in no headers.
    if program.adds.is_empty() {
        for ext in &program.externs {
            let params = if ext.params.is_empty() {
                "void".to_string()
            } else {
                ext.params
                    .iter()
                    .map(|p| ctype_extern(&p.ty))
                    .collect::<Vec<_>>()
                    .join(", ")
            };
            out.push_str(&format!(
                "{} {}({});\n",
                ctype_extern(&ext.ret),
                ext.name,
                params
            ));
        }
        if !program.externs.is_empty() {
            out.push('\n');
        }
    }

    for f in &program.fns {
        if f.name == "main" {
            continue;
        }
        let params = if f.params.is_empty() {
            "void".to_string()
        } else {
            f.params
                .iter()
                .map(|p| ctype(&p.ty))
                .collect::<Vec<_>>()
                .join(", ")
        };
        out.push_str(&format!(
            "static {} fn_{}({});\n",
            ctype(&f.ret),
            mangle(&f.name),
            params
        ));
    }
    out.push('\n');

    for f in &program.fns {
        generator.emit_fn(f, &mut out);
    }

    out
}

struct Generator<'a> {
    program: &'a Program,
    file: &'a SourceFile,
    scopes: Vec<HashMap<String, String>>,
    next_id: usize,
    depth: usize,
    ret: Type,
}

impl<'a> Generator<'a> {
    // --------------------------------------------------------------- helpers

    fn line(&self, text: &str) -> String {
        format!("{}{}\n", "    ".repeat(self.depth), text)
    }

    fn bind(&mut self, name: &str) -> String {
        let id = self.next_id;
        self.next_id += 1;
        let cname = format!("l_{}_{}", mangle(name), id);
        self.scopes
            .last_mut()
            .expect("scope stack")
            .insert(name.to_string(), cname.clone());
        cname
    }

    fn lookup(&self, name: &str) -> Option<&String> {
        self.scopes.iter().rev().find_map(|s| s.get(name))
    }

    fn fresh_temp(&mut self) -> String {
        let id = self.next_id;
        self.next_id += 1;
        format!("t_{id}")
    }

    fn push_scope(&mut self) {
        self.scopes.push(HashMap::new());
    }

    fn pop_scope(&mut self) {
        self.scopes.pop();
    }

    fn ordered_structs(&self) -> Vec<&'a StructDef> {
        let structs: &'a [StructDef] = &self.program.structs;
        let n = structs.len();
        let mut map: HashMap<&str, usize> = HashMap::new();
        for (i, def) in structs.iter().enumerate() {
            map.insert(def.name.as_str(), i);
        }

        fn visit<'b>(
            index: usize,
            structs: &'b [StructDef],
            map: &HashMap<&str, usize>,
            visited: &mut Vec<bool>,
            out: &mut Vec<&'b StructDef>,
        ) {
            if visited[index] {
                return;
            }
            visited[index] = true;
            for field in &structs[index].fields {
                if let TypeKind::Named(name) = &field.ty.kind {
                    if let Some(&dep) = map.get(name.as_str()) {
                        visit(dep, structs, map, visited, out);
                    }
                }
            }
            out.push(&structs[index]);
        }

        let mut visited = vec![false; n];
        let mut out = Vec::new();
        for i in 0..n {
            visit(i, structs, &map, &mut visited, &mut out);
        }
        out
    }

    // -------------------------------------------------------------- functions

    fn emit_fn(&mut self, f: &FnDef, out: &mut String) {
        self.scopes.clear();
        self.push_scope();
        self.ret = f.ret.clone();
        self.depth = 1;

        let mut header = String::new();
        if f.name == "main" {
            header.push_str("int main(void) {\n");
        } else {
            let mut params = Vec::new();
            for p in &f.params {
                let cname = self.bind(&p.name);
                params.push(format!("{} {}", ctype(&p.ty), cname));
            }
            header.push_str(&format!(
                "static {} fn_{}({}) {{\n",
                ctype(&f.ret),
                mangle(&f.name),
                if params.is_empty() {
                    "void".to_string()
                } else {
                    params.join(", ")
                }
            ));
        }
        out.push_str(&header);

        let mut body = String::new();
        for stmt in &f.body.stmts {
            body.push_str(&self.emit_stmt(stmt));
        }

        match &f.body.value {
            Some(value) => {
                let value_ty = value.ty.clone().unwrap_or_else(|| Type::void(value.span));
                if !f.ret.is_void() && !value_ty.is_void() {
                    let code = self.emit_as(value, &f.ret);
                    body.push_str(&self.line(&format!("return {code};")));
                } else {
                    let code = self.emit_expr(value);
                    body.push_str(&self.line(&format!("{code};")));
                    if !f.ret.is_void() {
                        body.push_str(&self.line(&format!(
                            "q_unreachable(\"function `{}` did not return\");",
                            escape(&f.name)
                        )));
                    }
                }
            }
            None => {
                if !f.ret.is_void() {
                    body.push_str(&self.line(&format!(
                        "q_unreachable(\"function `{}` reached the end without returning\");",
                        escape(&f.name)
                    )));
                } else if f.name == "main" {
                    body.push_str(&self.line("return 0;"));
                }
            }
        }

        out.push_str(&body);
        out.push_str("}\n\n");
        self.pop_scope();
    }

    // ------------------------------------------------------------- statements

    fn emit_stmt(&mut self, stmt: &Stmt) -> String {
        match stmt {
            Stmt::Let {
                name, ty, value, ..
            } => {
                let ty = match ty {
                    Some(ty) => ty.clone(),
                    None => value.ty.clone().unwrap_or_else(|| Type::void(value.span)),
                };
                let value_code = self.emit_as(value, &ty);
                let cname = self.bind(name);
                self.line(&format!("{} {} = {};", ctype(&ty), cname, value_code))
            }
            Stmt::Assign {
                target,
                value,
                op,
                ..
            } => {
                let ty = target
                    .ty
                    .clone()
                    .unwrap_or_else(|| Type::void(target.span));
                let target_code = self.emit_expr(target);
                let value_code = self.emit_as(value, &ty);
                match op {
                    None => self.line(&format!("{target_code} = {value_code};")),
                    Some(op) => {
                        // Evaluate the place once, then combine through a pointer so
                        // `items[i] += 1` does not look up `i` twice.
                        let ptr = self.fresh_temp();
                        let combined = match op {
                            BinOp::Add if ty.kind == TypeKind::Str => {
                                format!("q_str_concat((*{ptr}), {value_code})")
                            }
                            BinOp::Add
                            | BinOp::Sub
                            | BinOp::Mul
                            | BinOp::Div
                            | BinOp::Rem => {
                                if ty.kind == TypeKind::Float {
                                    format!("((*{ptr}) {} {value_code})", op.symbol())
                                } else {
                                    let fn_name = match op {
                                        BinOp::Add => "q_add_i64",
                                        BinOp::Sub => "q_sub_i64",
                                        BinOp::Mul => "q_mul_i64",
                                        BinOp::Div => "q_div_i64",
                                        BinOp::Rem => "q_mod_i64",
                                        _ => unreachable!(),
                                    };
                                    format!("{fn_name}((*{ptr}), {value_code})")
                                }
                            }
                            _ => unreachable!("compound assignment operator"),
                        };
                        self.line(&format!(
                            "{{ {}* {ptr} = &({target_code}); *{ptr} = {combined}; }}",
                            ctype(&ty)
                        ))
                    }
                }
            }
            Stmt::Expr(expr) => match &expr.kind {
                ExprKind::If { .. } => self.emit_if_stmt(expr),
                ExprKind::While { .. } => self.emit_while_stmt(expr),
                ExprKind::For { .. } => self.emit_for_stmt(expr),
                ExprKind::Block(block) => {
                    let body = self.emit_block_body(block, None, false);
                    format!("{}{{\n{}{}}}\n", "    ".repeat(self.depth), body, "    ".repeat(self.depth))
                }
                _ => {
                    let code = self.emit_expr(expr);
                    self.line(&format!("{code};"))
                }
            },
            Stmt::Return { value, .. } => match value {
                Some(value) => {
                    let ret = self.ret.clone();
                    let code = self.emit_as(value, &ret);
                    self.line(&format!("return {code};"))
                }
                None => self.line("return;"),
            },
            Stmt::Break(_) => self.line("break;"),
            Stmt::Continue(_) => self.line("continue;"),
        }
    }

    /// Emit a block as statements. `assign` makes the block's value assign to a
    /// temporary instead of being discarded; `ensure_value` makes the block safe
    /// to use as the last expression of a GNU statement expression.
    fn emit_block_body(
        &mut self,
        block: &Block,
        assign: Option<(&str, &Type)>,
        ensure_value: bool,
    ) -> String {
        self.push_scope();
        self.depth += 1;
        let mut out = String::new();
        for stmt in &block.stmts {
            out.push_str(&self.emit_stmt(stmt));
        }
        match (&block.value, assign) {
            (Some(value), Some((target, ty))) => {
                let code = self.emit_as(value, ty);
                out.push_str(&self.line(&format!("{target} = {code};")));
            }
            (Some(value), None) => {
                let code = self.emit_expr(value);
                out.push_str(&self.line(&format!("{code};")));
            }
            (None, _) => {
                if ensure_value {
                    out.push_str(&self.line("(void)0;"));
                }
            }
        }
        self.depth -= 1;
        self.pop_scope();
        out
    }

    fn emit_block_expr(&mut self, block: &Block) -> String {
        let body = self.emit_block_body(block, None, true);
        format!("({{ {body} }})")
    }

    fn emit_if_stmt(&mut self, expr: &Expr) -> String {
        let ExprKind::If {
            cond,
            then_block,
            else_branch,
        } = &expr.kind
        else {
            unreachable!("emit_if_stmt on non-if");
        };

        let cond = self.emit_expr(cond);
        let mut out = self.line(&format!("if ({cond}) {{"));
        out.push_str(&self.emit_block_body(then_block, None, false));
        if let Some(else_branch) = else_branch {
            out.push_str(&self.line("} else {"));
            match &else_branch.kind {
                ExprKind::If { .. } => out.push_str(&self.emit_if_stmt(else_branch)),
                ExprKind::Block(block) => {
                    out.push_str(&self.emit_block_body(block, None, false));
                }
                _ => {
                    let code = self.emit_expr(else_branch);
                    out.push_str(&self.line(&format!("{code};")));
                }
            }
        }
        out.push_str(&self.line("}"));
        out
    }

    /// Emit an `if` expression that assigns its result to `target`.
    fn emit_if_assign(&mut self, expr: &Expr, target: &str, ty: &Type) -> String {
        let ExprKind::If {
            cond,
            then_block,
            else_branch,
        } = &expr.kind
        else {
            unreachable!("emit_if_assign on non-if");
        };
        let else_branch = else_branch
            .as_ref()
            .expect("value-position if must have an else branch");

        let cond = self.emit_expr(cond);
        let mut out = self.line(&format!("if ({cond}) {{"));
        out.push_str(&self.emit_block_body(then_block, Some((target, ty)), false));
        out.push_str(&self.line("} else {"));
        match &else_branch.kind {
            ExprKind::If { .. } => out.push_str(&self.emit_if_assign(else_branch, target, ty)),
            ExprKind::Block(block) => {
                out.push_str(&self.emit_block_body(block, Some((target, ty)), false));
            }
            _ => {
                let code = self.emit_as(else_branch, ty);
                out.push_str(&self.line(&format!("{target} = {code};")));
            }
        }
        out.push_str(&self.line("}"));
        out
    }

    fn emit_while_stmt(&mut self, expr: &Expr) -> String {
        let ExprKind::While { cond, body } = &expr.kind else {
            unreachable!("emit_while_stmt on non-while");
        };
        let cond = self.emit_expr(cond);
        let mut out = self.line(&format!("while ({cond}) {{"));
        out.push_str(&self.emit_block_body(body, None, false));
        out.push_str(&self.line("}"));
        out
    }

    fn emit_for_stmt(&mut self, expr: &Expr) -> String {
        let ExprKind::For { var, iter, body } = &expr.kind else {
            unreachable!("emit_for_stmt on non-for");
        };
        match iter {
            ForIter::Range { start, end } => {
                let start = self.emit_expr(start);
                let end = self.emit_expr(end);
                let end_tmp = self.fresh_temp();
                let mut out = self.line(&format!("int64_t {end_tmp} = {end};"));
                self.push_scope();
                let var_c = self.bind(var);
                out.push_str(&self.line(&format!(
                    "for (int64_t {var_c} = {start}; {var_c} < {end_tmp}; {var_c}++) {{"
                )));
                out.push_str(&self.emit_block_body(body, None, false));
                out.push_str(&self.line("}"));
                self.pop_scope();
                out
            }
            ForIter::Array(array_expr) => {
                let elem_ty = match array_expr.ty.clone().map(|t| t.kind) {
                    Some(TypeKind::Array(elem)) => *elem,
                    _ => Type::error(expr.span),
                };
                let array = self.emit_expr(array_expr);
                let arr_tmp = self.fresh_temp();
                let len_tmp = self.fresh_temp();
                let idx_tmp = self.fresh_temp();
                let mut out = self.line(&format!("QArr* {arr_tmp} = {array};"));
                out.push_str(&self.line(&format!(
                    "int64_t {len_tmp} = q_arr_len({arr_tmp});"
                )));
                self.push_scope();
                let var_c = self.bind(var);
                out.push_str(&self.line(&format!(
                    "for (int64_t {idx_tmp} = 0; {idx_tmp} < {len_tmp}; {idx_tmp}++) {{"
                )));
                self.depth += 1;
                out.push_str(&self.line(&format!(
                    "{} {var_c} = *({}*)q_arr_at({arr_tmp}, {idx_tmp});",
                    ctype(&elem_ty),
                    ctype(&elem_ty)
                )));
                self.depth -= 1;
                out.push_str(&self.emit_block_body(body, None, false));
                out.push_str(&self.line("}"));
                self.pop_scope();
                out
            }
        }
    }

    // ------------------------------------------------------------ expressions

    fn emit_expr(&mut self, expr: &Expr) -> String {
        match &expr.kind {
            ExprKind::Int(value) => {
                if *value == i64::MIN {
                    "((int64_t)0x8000000000000000ULL)".to_string()
                } else {
                    format!("({value}LL)")
                }
            }
            ExprKind::Float(value) => format!("({value:?})"),
            ExprKind::Bool(value) => value.to_string(),
            ExprKind::Str(parts) => self.emit_string(parts),
            ExprKind::Ident(name) => self
                .lookup(name)
                .cloned()
                .unwrap_or_else(|| format!("l_{}_0", mangle(name))),
            ExprKind::Array(items) => self.emit_array(expr, items),
            ExprKind::Binary { op, lhs, rhs } => self.emit_binary(expr, *op, lhs, rhs),
            ExprKind::Unary { op, expr: inner } => {
                let code = self.emit_expr(inner);
                match op {
                    UnOp::Neg => match inner.ty.as_ref().map(|t| &t.kind) {
                        Some(TypeKind::Float) => format!("(-{code})"),
                        _ => format!("q_neg_i64({code})"),
                    },
                    UnOp::Not => format!("(!{code})"),
                }
            }
            ExprKind::Call { name, args } => self.emit_call(expr, name, args),
            ExprKind::Field { object, name } => {
                let object = self.emit_expr(object);
                format!("({object}).m_{}", mangle(name))
            }
            ExprKind::Index { object, index } => {
                let elem = expr
                    .ty
                    .clone()
                    .unwrap_or_else(|| Type::error(expr.span));
                let object = self.emit_expr(object);
                let index = self.emit_expr(index);
                format!(
                    "(*({}*)q_arr_at({object}, {index}))",
                    ctype(&elem)
                )
            }
            ExprKind::StructLit { name, fields } => self.emit_struct_lit(expr, name, fields),
            ExprKind::If { .. } => {
                let ty = expr
                    .ty
                    .clone()
                    .unwrap_or_else(|| Type::void(expr.span));
                if ty.is_void() {
                    let stmt = self.emit_if_stmt(expr);
                    format!("({{ {stmt} (void)0; }})")
                } else {
                    let tmp = self.fresh_temp();
                    let mut out = format!("({{ {} {}; ", ctype(&ty), tmp);
                    out.push_str(&self.emit_if_assign(expr, &tmp, &ty));
                    out.push_str(&format!(" {tmp}; }})"));
                    out
                }
            }
            ExprKind::Block(block) => self.emit_block_expr(block),
            ExprKind::While { .. } => {
                let stmt = self.emit_while_stmt(expr);
                format!("({{ {stmt} (void)0; }})")
            }
            ExprKind::For { .. } => {
                let stmt = self.emit_for_stmt(expr);
                format!("({{ {stmt} (void)0; }})")
            }
        }
    }

    fn emit_as(&mut self, expr: &Expr, target: &Type) -> String {
        let code = self.emit_expr(expr);
        if let Some(actual) = &expr.ty {
            if actual.kind == TypeKind::Int && target.kind == TypeKind::Float {
                return format!("((double){code})");
            }
        }
        code
    }

    fn emit_string(&mut self, parts: &[StrPart]) -> String {
        let mut pieces = Vec::new();
        for part in parts {
            match part {
                StrPart::Text(text) => pieces.push(format!(
                    "q_str_lit({}, {})",
                    c_string(text),
                    text.as_bytes().len()
                )),
                StrPart::Expr(expr) => {
                    let code = self.emit_expr(expr);
                    match expr.ty.as_ref().map(|t| &t.kind) {
                        Some(TypeKind::Str) => pieces.push(code),
                        Some(TypeKind::Int) => pieces.push(format!("q_str_of_i64({code})")),
                        Some(TypeKind::Float) => pieces.push(format!("q_str_of_f64({code})")),
                        Some(TypeKind::Bool) => pieces.push(format!("q_str_of_bool({code})")),
                        _ => pieces.push(format!("q_str_lit(\"\", 0)")),
                    }
                }
            }
        }

        if pieces.is_empty() {
            return "q_str_lit(\"\", 0)".to_string();
        }
        let mut iter = pieces.into_iter();
        let mut result = iter.next().unwrap();
        for piece in iter {
            result = format!("q_str_concat({result}, {piece})");
        }
        result
    }

    fn emit_array(&mut self, expr: &Expr, items: &[Expr]) -> String {
        let elem = match expr.ty.as_ref().map(|t| &t.kind) {
            Some(TypeKind::Array(inner)) => (**inner).clone(),
            _ => Type::error(expr.span),
        };
        let elem_c = ctype(&elem);
        if items.is_empty() {
            return format!("q_arr_new(sizeof({elem_c}), 4)");
        }
        let values = items
            .iter()
            .map(|item| self.emit_as(item, &elem))
            .collect::<Vec<_>>()
            .join(", ");
        format!(
            "q_arr_from(({elem_c}[]){{{values}}}, {}, sizeof({elem_c}))",
            items.len()
        )
    }

    fn emit_binary(&mut self, expr: &Expr, op: BinOp, lhs: &Expr, rhs: &Expr) -> String {
        let lhs_ty = lhs.ty.clone().unwrap_or_else(|| Type::error(expr.span));
        let rhs_ty = rhs.ty.clone().unwrap_or_else(|| Type::error(expr.span));
        let result_ty = expr.ty.clone().unwrap_or_else(|| Type::error(expr.span));

        match op {
            BinOp::Add if lhs_ty.kind == TypeKind::Str && rhs_ty.kind == TypeKind::Str => {
                let a = self.emit_expr(lhs);
                let b = self.emit_expr(rhs);
                format!("q_str_concat({a}, {b})")
            }
            BinOp::Add
            | BinOp::Sub
            | BinOp::Mul
            | BinOp::Div
            | BinOp::Rem => {
                if result_ty.kind == TypeKind::Float {
                    let float_ty = Type::float(expr.span);
                    let a = self.emit_as(lhs, &float_ty);
                    let b = self.emit_as(rhs, &float_ty);
                    let symbol = op.symbol();
                    return format!("({a} {symbol} {b})");
                }
                let fn_name = match op {
                    BinOp::Add => "q_add_i64",
                    BinOp::Sub => "q_sub_i64",
                    BinOp::Mul => "q_mul_i64",
                    BinOp::Div => "q_div_i64",
                    BinOp::Rem => "q_mod_i64",
                    _ => unreachable!(),
                };
                let a = self.emit_expr(lhs);
                let b = self.emit_expr(rhs);
                format!("{fn_name}({a}, {b})")
            }
            BinOp::Eq | BinOp::Ne => {
                if lhs_ty.kind == TypeKind::Str && rhs_ty.kind == TypeKind::Str {
                    let a = self.emit_expr(lhs);
                    let b = self.emit_expr(rhs);
                    let eq = format!("q_str_eq({a}, {b})");
                    return if op == BinOp::Eq {
                        eq
                    } else {
                        format!("(!{eq})")
                    };
                }
                let a = self.emit_expr(lhs);
                let b = self.emit_expr(rhs);
                let symbol = op.symbol();
                format!("({a} {symbol} {b})")
            }
            BinOp::Lt | BinOp::Le | BinOp::Gt | BinOp::Ge => {
                let a = self.emit_expr(lhs);
                let b = self.emit_expr(rhs);
                if lhs_ty.kind == TypeKind::Str && rhs_ty.kind == TypeKind::Str {
                    let symbol = op.symbol();
                    return format!("(q_str_cmp({a}, {b}) {symbol} 0)");
                }
                let symbol = op.symbol();
                format!("({a} {symbol} {b})")
            }
            BinOp::And | BinOp::Or => {
                let a = self.emit_expr(lhs);
                let b = self.emit_expr(rhs);
                let symbol = op.symbol();
                format!("({a} {symbol} {b})")
            }
        }
    }

    fn emit_struct_lit(&mut self, expr: &Expr, name: &str, fields: &[(String, Expr)]) -> String {
        let Some(def) = self.program.structs.iter().find(|s| s.name == name) else {
            return "0".to_string();
        };
        let mut parts = Vec::new();
        for field in &def.fields {
            if let Some((_, value)) = fields.iter().find(|(n, _)| n == &field.name) {
                let code = self.emit_as(value, &field.ty);
                parts.push(format!(".m_{} = {}", mangle(&field.name), code));
            }
        }
        let _ = expr;
        format!("((s_{}){{{}}})", mangle(&def.name), parts.join(", "))
    }

    fn emit_call(&mut self, expr: &Expr, name: &str, args: &[Expr]) -> String {
        match name {
            "print" | "println" => {
                let mut parts = Vec::new();
                if let Some(arg) = args.first() {
                    parts.push(self.emit_print_value(arg));
                }
                if name == "println" {
                    parts.push("q_print_newline()".to_string());
                }
                match parts.len() {
                    0 => "(void)0".to_string(),
                    1 => parts.pop().unwrap(),
                    _ => format!("({})", parts.join(", ")),
                }
            }
            "len" => {
                let arg = &args[0];
                let code = self.emit_expr(arg);
                match arg.ty.as_ref().map(|t| &t.kind) {
                    Some(TypeKind::Str) => format!("q_str_len({code})"),
                    _ => format!("q_arr_len({code})"),
                }
            }
            "push" => {
                let elem = match args[0].ty.as_ref().map(|t| &t.kind) {
                    Some(TypeKind::Array(inner)) => (**inner).clone(),
                    _ => Type::error(expr.span),
                };
                let array = self.emit_expr(&args[0]);
                let elem_c = ctype(&elem);
                let value = self.emit_as(&args[1], &elem);
                format!("q_arr_push({array}, &({elem_c}){{{value}}})")
            }
            "str" => {
                let arg = &args[0];
                let code = self.emit_expr(arg);
                match arg.ty.as_ref().map(|t| &t.kind) {
                    Some(TypeKind::Str) => code,
                    Some(TypeKind::Bool) => format!("q_str_of_bool({code})"),
                    Some(TypeKind::Float) => format!("q_str_of_f64({code})"),
                    _ => format!("q_str_of_i64({code})"),
                }
            }
            "int" => {
                let arg = &args[0];
                let code = self.emit_expr(arg);
                match arg.ty.as_ref().map(|t| &t.kind) {
                    Some(TypeKind::Float) => format!("q_f64_to_i64({code})"),
                    Some(TypeKind::Bool) => format!("((int64_t)({code}))"),
                    Some(TypeKind::Str) => format!("q_str_to_i64({code})"),
                    _ => code,
                }
            }
            "float" => {
                let arg = &args[0];
                let code = self.emit_expr(arg);
                match arg.ty.as_ref().map(|t| &t.kind) {
                    Some(TypeKind::Float) => code,
                    Some(TypeKind::Str) => format!("q_str_to_f64({code})"),
                    _ => format!("((double)({code}))"),
                }
            }
            "abs" => {
                let arg = &args[0];
                let code = self.emit_expr(arg);
                match arg.ty.as_ref().map(|t| &t.kind) {
                    Some(TypeKind::Float) => format!("fabs({code})"),
                    _ => format!("q_abs_i64({code})"),
                }
            }
            "min" | "max" => {
                let result_float = expr
                    .ty
                    .as_ref()
                    .map(|t| t.kind == TypeKind::Float)
                    .unwrap_or(false);
                if result_float {
                    let float_ty = Type::float(expr.span);
                    let a = self.emit_as(&args[0], &float_ty);
                    let b = self.emit_as(&args[1], &float_ty);
                    let fn_name = if name == "min" { "q_min_f64" } else { "q_max_f64" };
                    format!("{fn_name}({a}, {b})")
                } else {
                    let a = self.emit_expr(&args[0]);
                    let b = self.emit_expr(&args[1]);
                    let fn_name = if name == "min" { "q_min_i64" } else { "q_max_i64" };
                    format!("{fn_name}({a}, {b})")
                }
            }
            "read_line" => "q_read_line()".to_string(),
            "read_int" => "q_read_int()".to_string(),
            "read_float" => "q_read_float()".to_string(),
            "assert" => {
                let code = self.emit_expr(&args[0]);
                let line = self.file.line_col(expr.span.start).0 + 1;
                let message = format!("{}:{}: assertion failed", self.file.name, line);
                format!("q_assert({code}, {})", c_string(&message))
            }
            _ => {
                // Check user functions first.
                if let Some(f) = self.program.fns.iter().find(|f| f.name == name) {
                    let params = f.params.clone();
                    let args = args
                        .iter()
                        .zip(params.iter())
                        .map(|(arg, param)| self.emit_as(arg, &param.ty))
                        .collect::<Vec<_>>()
                        .join(", ");
                    return format!("fn_{}({})", mangle(name), args);
                }
                // Then extern C functions (called by their real name).
                if let Some(ext) = self.program.externs.iter().find(|e| e.name == name) {
                    let params = ext.params.clone();
                    let args = args
                        .iter()
                        .zip(params.iter())
                        .map(|(arg, param)| self.emit_extern_arg(arg, &param.ty))
                        .collect::<Vec<_>>()
                        .join(", ");
                    return format!("{name}({args})");
                }
                "0".to_string()
            }
        }
    }

    /// Convert a Quill argument to the C representation an extern function
    /// expects. Quill `str` is a `QStr*`, but C libraries want `const char*`.
    fn emit_extern_arg(&mut self, expr: &Expr, target: &Type) -> String {
        let code = self.emit_expr(expr);
        if target.kind == TypeKind::Str && expr.ty.as_ref().map(|t| &t.kind) == Some(&TypeKind::Str) {
            return format!("q_str_cstr({code})");
        }
        if target.kind == TypeKind::Float && expr.ty.as_ref().map(|t| &t.kind) == Some(&TypeKind::Int) {
            return format!("((double){code})");
        }
        code
    }

    fn emit_print_value(&mut self, expr: &Expr) -> String {
        let code = self.emit_expr(expr);
        match expr.ty.as_ref().map(|t| &t.kind) {
            Some(TypeKind::Int) => format!("q_print_i64({code})"),
            Some(TypeKind::Float) => format!("q_print_f64({code})"),
            Some(TypeKind::Bool) => format!("q_print_bool({code})"),
            Some(TypeKind::Str) => format!("q_print_str({code})"),
            Some(TypeKind::Array(inner)) => match &inner.kind {
                TypeKind::Int => format!("q_print_arr_i64({code})"),
                TypeKind::Float => format!("q_print_arr_f64({code})"),
                TypeKind::Bool => format!("q_print_arr_bool({code})"),
                TypeKind::Str => format!("q_print_arr_str({code})"),
                _ => "((void)0)".to_string(),
            },
            _ => "((void)0)".to_string(),
        }
    }
}

fn ctype(ty: &Type) -> String {
    match &ty.kind {
        TypeKind::Int => "int64_t".to_string(),
        TypeKind::Float => "double".to_string(),
        TypeKind::Bool => "bool".to_string(),
        TypeKind::Str => "QStr*".to_string(),
        TypeKind::Void => "void".to_string(),
        TypeKind::Error => "void".to_string(),
        TypeKind::Array(_) => "QArr*".to_string(),
        TypeKind::Named(name) => format!("s_{}", mangle(name)),
    }
}

/// C type for an extern function signature. Quill `str` crosses the FFI
/// boundary as a NUL-terminated `const char*`, and crossings are converted with
/// `q_str_cstr`.
fn ctype_extern(ty: &Type) -> String {
    match &ty.kind {
        TypeKind::Str => "const char*".to_string(),
        _ => ctype(ty),
    }
}

fn mangle(name: &str) -> String {
    let mut out = String::new();
    for byte in name.bytes() {
        if byte.is_ascii_alphanumeric() || byte == b'_' {
            out.push(byte as char);
        } else {
            out.push_str(&format!("_{byte:02x}"));
        }
    }
    if out.is_empty() {
        out.push('_');
    }
    out
}

fn c_string(text: &str) -> String {
    let mut out = String::from("\"");
    for byte in text.bytes() {
        match byte {
            b'"' => out.push_str("\\\""),
            b'\\' => out.push_str("\\\\"),
            b'\n' => out.push_str("\\n"),
            b'\t' => out.push_str("\\t"),
            b'\r' => out.push_str("\\r"),
            0x20..=0x7e => out.push(byte as char),
            _ => out.push_str(&format!("\\{byte:03o}")),
        }
    }
    out.push('"');
    out
}

fn escape(text: &str) -> String {
    let mut out = String::new();
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            _ => out.push(c),
        }
    }
    out
}
